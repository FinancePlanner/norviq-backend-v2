package portfoliomgmt

import "testing"

// Expected values were read from the parity Vapor (macOS Foundation).
func TestParseDateMatchesFoundation(t *testing.T) {
	cases := map[string]string{
		"2026-09-01":                "2026-09-01T00:00:00.000Z",
		"2026-09-01T10:00:00Z":      "2026-09-01T10:00:00.000Z",
		"2026-09-01T10:00:00z":      "2026-09-01T10:00:00.000Z",
		"2026-09-01T10:00:00+0100":  "2026-09-01T09:00:00.000Z",
		"2026-09-01T10:00:00+01":    "2026-09-01T09:00:00.000Z",
		"2026-09-01T10:00:00-05:30": "2026-09-01T15:30:00.000Z",
		"2026-09-01T10:00:00+14:00": "2026-08-31T20:00:00.000Z",
		"2026-09-01T10:00:00 Z":     "2026-09-01T10:00:00.000Z",
		"2026-09-01T10:00:00GMT":    "2026-09-01T10:00:00.000Z",
		"2026-09-01T9:00:00Z":       "2026-09-01T09:00:00.000Z",
		"2026-9-1T10:00:00Z":        "2026-09-01T10:00:00.000Z",
		"2026-09-01T24:00:00Z":      "2026-09-02T00:00:00.000Z",
		"2026-09-01T25:00:00Z":      "2026-09-01T00:00:00.000Z",
		"2026-09-01T10:60:00Z":      "2026-09-01T00:00:00.000Z",
		"2026-09-01T10:00Z":         "2026-09-01T00:00:00.000Z",
		"2026-09-01T10:00:00.5Z":    "2026-09-01T00:00:00.000Z",
		"2026-09-01T10:00:00+1:00":  "2026-09-01T00:00:00.000Z",
		"2026-09-01t10:00:00z":      "2026-09-01T00:00:00.000Z",
		"2026-09-01T10:00:00":       "2026-09-01T00:00:00.000Z",
		"2026-09-01 junk":           "2026-09-01T00:00:00.000Z",
		" 2026-09-01":               "2026-09-01T00:00:00.000Z",
		"2026-9-1":                  "2026-09-01T00:00:00.000Z",
		"2026-009-01":               "2026-09-01T00:00:00.000Z",
		"2026-09-001":               "2026-09-01T00:00:00.000Z",
		"2026/09/01":                "2026-09-01T00:00:00.000Z",
		"2026.09.01":                "2026-09-01T00:00:00.000Z",
		"2026 09 01":                "2026-09-01T00:00:00.000Z",
		"2026-02-30":                "2026-03-02T00:00:00.000Z",
		"2026-09-31":                "2026-10-01T00:00:00.000Z",
		"999-01-01":                 "0999-01-01T00:00:00.000Z",
		"20260901":                  "",
		"2026-13-01":                "",
		"2026-09-32":                "",
		"2026-09-00":                "",
		"2026-00-10":                "",
		"2026x09x01":                "",
		"2026--09-01":               "",
		"a2026-09-01":               "",
		"+2026-09-01":               "",
		"2026-09":                   "",
		"2026-W36-1":                "",
		"":                          "",
	}
	for in, want := range cases {
		got, err := parseDate(in)
		switch {
		case want == "" && err == nil:
			t.Errorf("%q: parsed %v, want Invalid date.", in, got)
		case want != "" && err != nil:
			t.Errorf("%q: %v, want %s", in, err, want)
		case want != "" && formatOptional(&got) != want:
			t.Errorf("%q: %s, want %s", in, formatOptional(&got), want)
		}
	}
}
