package export

import "image/color"

// Palette is the set of brand colors a renderer needs, per docs/precision-identity.md.
type Palette struct {
	Page, Card, Elevated, Rule, Gold, Text, Muted, Gain, Loss, Flat color.RGBA
}

func rgb(r, g, b uint8) color.RGBA { return color.RGBA{R: r, G: g, B: b, A: 0xFF} }

// Dark is the flagship palette.
var Dark = Palette{
	Page: rgb(0x0A, 0x10, 0x1A), Card: rgb(0x11, 0x1B, 0x2B), Elevated: rgb(0x1B, 0x29, 0x40),
	Rule: rgb(0x34, 0x42, 0x58), Gold: rgb(0xD8, 0xB4, 0x77), Text: rgb(0xE9, 0xE9, 0xE5),
	Muted: rgb(0x9D, 0xA9, 0xB8), Gain: rgb(0x42, 0xB8, 0x94), Loss: rgb(0xE1, 0x6D, 0x75),
	Flat: rgb(0xA6, 0xAF, 0xBA),
}

