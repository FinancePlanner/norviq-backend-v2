// Exact values (Python Fraction(x)**n rounded once): Pow is correctly
// rounded where Darwin's libm is one ULP off.
func TestPowCorrectlyRounded(t *testing.T) {
	for _, c := range []struct{ x, y, want float64 }{
		{0.9583157309148174, 105, 0.011439441152870749},
		{1.1230130325022596, 65, 1883.7000810845718},
		{1.826094487144166, 89, 1.886117904876924e+23},
		{1.07, 0, 1},
		{1, 0.5, 1},
	} {
		if got := Pow(c.x, c.y); got != c.want {
			t.Errorf("Pow(%v, %v) = %v, want %v", c.x, c.y, got, c.want)
		}
	}
	if got, want := Pow(1.07, 1.0/12.0), math.Pow(1.07, 1.0/12.0); math.Abs(got-want) > 1e-15 {
		t.Fatal(got, want)
	}
}

// TestPowAgainstDarwin compares Pow with a file of Darwin pow results
// (lines "xbits ybits resultbits"), generated by a Swift script. Darwin is
// not always correctly rounded, so the bar is a mismatch rate, not zero.
func TestPowAgainstDarwin(t *testing.T) {
	path := os.Getenv("POW_CASES")
	if path == "" {
		t.Skip("POW_CASES not set")
	}
	f, err := os.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	bad, n := 0, 0
	for sc.Scan() {
		p := strings.Fields(sc.Text())
		xb, _ := strconv.ParseUint(p[0], 10, 64)
		yb, _ := strconv.ParseUint(p[1], 10, 64)
		wb, _ := strconv.ParseUint(p[2], 10, 64)
		n++
		if math.Float64bits(Pow(math.Float64frombits(xb), math.Float64frombits(yb))) != wb {
			bad++
		}
	}
	t.Logf("%d cases, %d mismatches", n, bad)
	if bad*100 > n {
		t.Fatal("more than 1% mismatches")
	}
}
