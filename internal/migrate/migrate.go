// Package migrate runs the goose migrations, and adopts a database the Vapor
// backend already migrated.
//
// Migration 00001 is a baseline: exactly the schema Vapor's Fluent
// migrations produce. On a fresh database goose runs it. On a database that
// has `_fluent_migrations` and no goose table, every Fluent migration the
// baseline captured must already be applied; then the baseline is stamped as
// applied without running, and goose owns the schema from there.
package migrate

import (
	"context"
	"database/sql"
	_ "embed"
	"errors"
	"fmt"
	"io/fs"
	"log/slog"
	"strings"

	"norviq-api/db"

	"github.com/pressly/goose/v3"
)

//go:embed fluent_migrations.txt
var fluentMigrationsRaw string

// BaselineVersion is the goose version of 00001_baseline.sql.
const BaselineVersion = 1

func provider(conn *sql.DB) (*goose.Provider, error) {
	sub, err := fs.Sub(db.Migrations, "migrations")
	if err != nil {
		return nil, err
	}
	return goose.NewProvider(goose.DialectPostgres, conn, sub)
}

// Up adopts a Vapor database if needed, then applies pending migrations.
func Up(ctx context.Context, conn *sql.DB, logger *slog.Logger) error {
	if err := adoptVapor(ctx, conn, logger); err != nil {
		return err
	}
	p, err := provider(conn)
	if err != nil {
		return err
	}
	results, err := p.Up(ctx)
	for _, r := range results {
		logger.Info("migration applied", "version", r.Source.Version, "path", r.Source.Path, "duration", r.Duration)
	}
	return err
}

// Status logs each migration's state.
func Status(ctx context.Context, conn *sql.DB, logger *slog.Logger) error {
	p, err := provider(conn)
	if err != nil {
		return err
	}
	statuses, err := p.Status(ctx)
	if err != nil {
		return err
	}
	for _, s := range statuses {
		logger.Info("migration", "version", s.Source.Version, "path", s.Source.Path, "state", s.State, "applied_at", s.AppliedAt)
	}
	return nil
}

func tableExists(ctx context.Context, conn *sql.DB, name string) (bool, error) {
	var exists bool
	err := conn.QueryRowContext(ctx, `SELECT to_regclass($1) IS NOT NULL`, "public."+name).Scan(&exists)
	return exists, err
}

func adoptVapor(ctx context.Context, conn *sql.DB, logger *slog.Logger) error {
	hasGoose, err := tableExists(ctx, conn, goose.DefaultTablename)
	if err != nil || hasGoose {
		return err
	}
	hasFluent, err := tableExists(ctx, conn, "_fluent_migrations")
	if err != nil || !hasFluent {
		return err
	}

	applied := map[string]bool{}
	rows, err := conn.QueryContext(ctx, `SELECT name FROM _fluent_migrations`)
	if err != nil {
		return err
	}
	defer rows.Close()
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			return err
		}
		applied[name] = true
	}
	if err := rows.Err(); err != nil {
		return err
	}
	var missing []string
	for _, name := range ExpectedFluentMigrations() {
		if !applied[name] {
			missing = append(missing, name)
		}
	}
	if len(missing) > 0 {
		return fmt.Errorf("database is a Vapor database missing %d Fluent migrations the baseline assumes (first: %s); run the Vapor migrate job first", len(missing), missing[0])
	}
	if extra := len(applied) - len(ExpectedFluentMigrations()); extra > 0 {
		return errors.New("database has Fluent migrations newer than the baseline; port them to goose migrations before adopting")
	}

	logger.Info("adopting Vapor-migrated database: stamping goose baseline", "version", BaselineVersion)
	tx, err := conn.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback() }()
	stmts := []string{
		`CREATE TABLE goose_db_version (
			id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL,
			is_applied boolean NOT NULL,
			tstamp timestamp NOT NULL DEFAULT now()
		)`,
		`INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true)`,
		fmt.Sprintf(`INSERT INTO goose_db_version (version_id, is_applied) VALUES (%d, true)`, BaselineVersion),
	}
	for _, s := range stmts {
		if _, err := tx.ExecContext(ctx, s); err != nil {
			return err
		}
	}
	return tx.Commit()
}

// ExpectedFluentMigrations lists the Fluent migrations the baseline captures.
func ExpectedFluentMigrations() []string {
	var out []string
	for _, line := range strings.Split(fluentMigrationsRaw, "\n") {
		if line = strings.TrimSpace(line); line != "" {
			out = append(out, line)
		}
	}
	return out
}
