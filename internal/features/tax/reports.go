// reportStorage is TaxReportStorage.
type reportStorage interface {
	store(data []byte, userID, reportID uuid.UUID, format string) (string, error)
	delete(path string) error
	exists(path string) bool
}

// localReportStorage is LocalTaxReportStorage: <root>/<USER>/<REPORT>.<fmt>,
// directories 0700, files written atomically.
type localReportStorage struct{ root string }

// reportStorageFromEnv is configure.swift's TAX_REPORT_STORAGE_PATH, by
// default <working directory>/storage/tax-reports. Vapor and v2 must share
// this directory: a report generated by one is downloaded through the
// other.
func reportStorageFromEnv() reportStorage {
	root, ok := os.LookupEnv("TAX_REPORT_STORAGE_PATH")
	if !ok {
		wd, err := os.Getwd()
		if err != nil {
			wd = "."
		}
		root = filepath.Join(wd, "storage", "tax-reports")
	}
	return localReportStorage{root: root}
}

func (s localReportStorage) dir(userID uuid.UUID) string {
	root := s.root
	if !filepath.IsAbs(root) {
		if abs, err := filepath.Abs(root); err == nil {
			root = abs
		}
	}
	return filepath.Join(root, uuidString(userID))
}

func (s localReportStorage) store(data []byte, userID, reportID uuid.UUID, format string) (string, error) {
	dir := s.dir(userID)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	path := filepath.Join(dir, uuidString(reportID)+"."+format)
	tmp, err := os.CreateTemp(dir, ".tax-report-*")
	if err != nil {
		return "", err
	}
	_, werr := tmp.Write(data)
	cerr := tmp.Close()
	if werr != nil || cerr != nil {
		_ = os.Remove(tmp.Name())
		return "", errors.Join(werr, cerr)
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil { //nolint:gosec // Foundation's Data.write default
		_ = os.Remove(tmp.Name())
		return "", err
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		_ = os.Remove(tmp.Name())
		return "", err
	}
	return path, nil
}

func (localReportStorage) delete(path string) error {
	if _, err := os.Stat(path); err != nil {
		return nil //nolint:nilerr // FileManager.fileExists false: nothing to delete
	}
	return os.RemoveAll(path)
}

func (localReportStorage) exists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

func (h *handlers) registerReportReads(tax *echo.Group, read []echo.MiddlewareFunc) {
	tax.GET("/filing/preview", h.filingPreview, read...)
	tax.GET("/reports", h.listReports, read...)
	tax.GET("/reports/:reportId", h.getReport, read...)
	tax.GET("/reports/:reportId/download", h.downloadReport, read...)
}

func (h *handlers) registerReportWrites(tax *echo.Group, write []echo.MiddlewareFunc) {
	tax.POST("/reports", h.createReport, write...)
}

// reportResponse is TaxController.reportResponse.
func reportResponse(r taxdb.TaxReport, createdAt time.Time) ReportResponse {
	kind := r.Kind
	if !oneOf(kind, reportKinds) {
		kind = "transaction_workpaper"
	}
	format := r.Format
	if !oneOf(format, reportFormats) {
		format = "csv"
	}
	id := uuidString(r.ID)
	out := ReportResponse{
		ID: id, TaxYear: int(r.TaxYear), Kind: kind, Format: format, Status: r.Status,
		CreatedAt: isoDate(createdAt),
	}
	if r.ExpiresAt != nil {
		out.ExpiresAt = strPtr(isoDate(*r.ExpiresAt))
	}
	if r.Status == "ready" {
		out.DownloadPath = strPtr("/v1/tax/reports/" + id + "/download")
	}
	return out
}

// filingPreview is GET /v1/tax/filing/preview?taxYear=.
func (h *handlers) filingPreview(c *echo.Context) error {
	s, err := auth.Require(c)
	if err != nil {
		return err
	}
	raw, _ := lastQueryValue(c, "taxYear")
	taxYear, perr := strconv.Atoi(raw)
	if perr != nil || taxYear < 2000 || taxYear > 2100 {
		return httpx.BadRequest("taxYear is required.")
	}
	if err := h.requireFilingPackAccess(c, s.UserID, taxYear); err != nil {
		return err
	}
	pack, err := h.svc.buildFilingPack(c.Request().Context(), s.UserID, taxYear, newECBProvider())
	if err != nil {
		return err
	}
	return httpx.OK(c, filingPreviewResponse(pack))
}

// createReport is POST /v1/tax/reports: the report is queued (pending) for
// TaxReportGenerationPoller.
func (h *handlers) createReport(c *echo.Context) error {
	s, err := auth.Require(c)
	if err != nil {
		return err
	}
	var req ReportRequest
	if err := decodeBody(c, &req); err != nil {
		return err
	}
	ctx := c.Request().Context()
	if req.Kind == "annual_filing_pack" {
		// The pack is what a per-year purchase buys: exempt from the
		// monthly report quota.
		if err := h.requireFilingPackAccess(c, s.UserID, req.TaxYear); err != nil {
			return err
		}
	} else {
		if err := h.requireTaxPro(c, s.UserID); err != nil {
			return err
		}
		count, err := h.svc.q.CountActiveTaxReports(ctx, s.UserID)
		if err != nil {
			return err
		}
		if err := h.svc.ent.EnforceResourceLimit(ctx, entitlements.FeatureReportGenerations, s.UserID, int(count), 1); err != nil {
			return err
		}
	}
	now := h.svc.now()
	zeroAttempts := int64(0)
	row, err := h.svc.q.InsertTaxReport(ctx, taxdb.InsertTaxReportParams{
		ID: uuid.New(), UserID: s.UserID, TaxYear: int64(req.TaxYear), Kind: req.Kind, Format: req.Format,
		Status: "pending", AttemptCount: &zeroAttempts, NextAttemptAt: &now, Now: now,
	})
	if err != nil {
		return err
	}
	if err := h.svc.ent.IncrementUsage(ctx, entitlements.FeatureReportGenerations, s.UserID, 1); err != nil {
		return err
	}
	return httpx.OK(c, reportResponse(row, now))
}

func (h *handlers) listReports(c *echo.Context) error {
	s, err := auth.Require(c)
	if err != nil {
		return err
	}
	rows, err := h.svc.q.TaxReportsForUser(c.Request().Context(), s.UserID)
	if err != nil {
		return err
	}
	out := make([]ReportResponse, len(rows))
	for i := range rows {
		r := &rows[i]
		out[i] = reportResponse(*r, r.CreatedAt)
	}
	return httpx.OK(c, out)
}

func (h *handlers) getReport(c *echo.Context) error {
	r, err := h.ownedReport(c, false)
	if err != nil {
		return err
	}
	return httpx.OK(c, reportResponse(r, r.CreatedAt))
}

// ownedReport is TaxController.ownedReport: 404 unless the report is the
// caller's; then Pro (or, for the filing pack, the year's pack) when
// requiresPro.
func (h *handlers) ownedReport(c *echo.Context, requiresPro bool) (taxdb.TaxReport, error) {
	s, err := auth.Require(c)
	if err != nil {
		return taxdb.TaxReport{}, err
	}
	id, ok := pathUUID(c, "reportId")
	if !ok {
		return taxdb.TaxReport{}, httpx.NotFound("Tax report not found.")
	}
	r, err := h.svc.q.TaxReportForUser(c.Request().Context(), taxdb.TaxReportForUserParams{ID: id, UserID: s.UserID})
	if isNoRows(err) {
		return taxdb.TaxReport{}, httpx.NotFound("Tax report not found.")
	}
	if err != nil {
		return taxdb.TaxReport{}, err
	}
	if requiresPro {
		if r.Kind == "annual_filing_pack" {
			err = h.requireFilingPackAccess(c, s.UserID, int(r.TaxYear))
		} else {
			err = h.requireTaxPro(c, s.UserID)
		}
		if err != nil {
			return taxdb.TaxReport{}, err
		}
	}
	return r, nil
}

// downloadReport streams the stored file the way Vapor's
// FileIO.streamFile(at:) did: ETag "<mtime>-<size>", Last-Modified, a 304
// on a matching If-None-Match, and a single byte range.
func (h *handlers) downloadReport(c *echo.Context) error {
	r, err := h.ownedReport(c, true)
	if err != nil {
		return err
	}
	if r.Status != "ready" || r.FilePath == nil {
		return httpx.Conflict("Tax report is not ready.")
	}
	if r.ExpiresAt != nil && !r.ExpiresAt.After(h.svc.now()) {
		return httpx.Abort(http.StatusGone, "Tax report has expired.")
	}
	path := *r.FilePath
	if !h.storage.exists(path) {
		slog.Warn("tax_report.download_missing", "report_id", uuidString(r.ID))
		return httpx.Abort(http.StatusGone, "Tax report is no longer available.")
	}
	format := r.Format
	if format != "pdf" {
		format = "csv"
	}
	contentType := "text/csv; charset=utf-8"
	if format == "pdf" {
		contentType = "application/pdf"
	}
	return streamFile(c, path, contentType,
		"attachment; filename=\"norviq-tax-"+strconv.FormatInt(r.TaxYear, 10)+"-"+r.Kind+"."+format+"\"")
}

func streamFile(c *echo.Context, path, contentType, disposition string) error {
	req := c.Request()
	hdr := c.Response().Header()
	info, err := os.Stat(path)
	if err != nil {
		return c.NoContent(http.StatusInternalServerError)
	}
	size := info.Size()
	modified := info.ModTime()
	etag := "\"" + marketdata.SwiftDoubleString(float64(modified.UnixNano())/1e9) + "-" + strconv.FormatInt(size, 10) + "\""

	start, length := int64(0), size
	partial := false
	if raw := req.Header.Get("Range"); raw != "" {
		s, n, ok := parseSingleRange(raw, size)
		if !ok {
			return c.NoContent(http.StatusBadRequest)
		}
		if n >= 0 {
			start, length, partial = s, n, true
		}
	}
	hdr.Set("Last-Modified", modified.UTC().Format(http.TimeFormat))
	hdr.Set("ETag", etag)
	hdr.Set(echo.HeaderContentType, contentType)
	hdr.Set("Content-Disposition", disposition)
	if etag == req.Header.Get("If-None-Match") {
		hdr.Set(echo.HeaderContentLength, strconv.FormatInt(size, 10))
		return c.NoContent(http.StatusNotModified)
	}
	f, err := os.Open(path)
	if err != nil {
		return c.NoContent(http.StatusInternalServerError)
	}
	defer func() { _ = f.Close() }()
	status := http.StatusOK
	if partial {
		status = http.StatusPartialContent
		// Vapor adds the range unit as an Accept header (sic).
		hdr.Add("Accept", "bytes")
		hdr.Set("Content-Range", "bytes "+strconv.FormatInt(start, 10)+"-"+strconv.FormatInt(start+length-1, 10)+"/"+strconv.FormatInt(size, 10))
		if _, err := f.Seek(start, io.SeekStart); err != nil {
			return err
		}
	}
	hdr.Set(echo.HeaderContentLength, strconv.FormatInt(length, 10))
	c.Response().WriteHeader(status)
	_, err = io.CopyN(c.Response(), f, length)
	return err
}

// parseSingleRange reads a "bytes=" header with exactly one range. n < 0
// means "serve the whole file" (another unit or several ranges); ok false
// is Vapor's 400 for an unparsable or unsatisfiable range.
func parseSingleRange(raw string, size int64) (start, n int64, ok bool) {
	unit, spec, found := strings.Cut(strings.TrimSpace(raw), "=")
	if !found {
		return 0, 0, false
	}
	if strings.TrimSpace(unit) != "bytes" || strings.Contains(spec, ",") {
		return 0, -1, true
	}
	lo, hi, found := strings.Cut(strings.TrimSpace(spec), "-")
	if !found {
		return 0, 0, false
	}
	switch {
	case lo == "":
		tail, err := strconv.ParseInt(hi, 10, 64)
		if err != nil || tail <= 0 {
			return 0, 0, false
		}
		tail = min(tail, size)
		return size - tail, tail, true
	case hi == "":
		from, err := strconv.ParseInt(lo, 10, 64)
		if err != nil || from >= size || from < 0 {
			return 0, 0, false
		}
		return from, size - from, true
	default:
		from, err1 := strconv.ParseInt(lo, 10, 64)
		to, err2 := strconv.ParseInt(hi, 10, 64)
		if err1 != nil || err2 != nil || from < 0 || to < from || from >= size {
			return 0, 0, false
		}
		to = min(to, size-1)
		return from, to - from + 1, true
	}
}
