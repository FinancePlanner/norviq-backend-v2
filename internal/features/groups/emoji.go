// isEmojiCharacter is GroupsValidation.isEmoji for one grapheme: any scalar
// with Emoji_Presentation, or a multi-scalar character whose first scalar
// has the Emoji property (digits and `#` only count with a variation
// selector or keycap). Go has no Unicode emoji properties, so the tables
// below transcribe Unicode 15.1's emoji-data.txt.
func isEmojiCharacter(c string) bool {
	rs := []rune(c)
	for _, r := range rs {
		if unicode.Is(emojiPresentation, r) {
			return true
		}
	}
	return len(rs) > 1 && (unicode.Is(emojiPresentation, rs[0]) || unicode.Is(emojiTextDefault, rs[0]))
}

func r16(lo, hi uint16) unicode.Range16 { return unicode.Range16{Lo: lo, Hi: hi, Stride: 1} }
func r32(lo, hi uint32) unicode.Range32 { return unicode.Range32{Lo: lo, Hi: hi, Stride: 1} }

