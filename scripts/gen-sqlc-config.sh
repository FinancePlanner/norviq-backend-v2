#!/usr/bin/env bash
# Regenerates sqlc.yaml with one package per directory under db/queries/.
# db/queries/<name>/*.sql generates internal/store/<name>db (core -> store).
# Run via `make generate`; never edit sqlc.yaml by hand.
set -euo pipefail
cd "$(git rev-parse --show-toplevel 2>/dev/null || dirname "$0"/..)"
{
  echo '# GENERATED by scripts/gen-sqlc-config.sh from db/queries/*/ — do not edit.'
  echo 'version: "2"'
  echo 'sql:'
  for dir in db/queries/*/; do
    name="$(basename "$dir")"
    if [[ "$name" == "core" ]]; then pkg=store; out=internal/store; else pkg="${name}db"; out="internal/store/${name}db"; fi
    sed -e "s#__QUERIES__#${dir%/}#" -e "s#__PACKAGE__#${pkg}#" -e "s#__OUT__#${out}#" scripts/sqlc-entry.tmpl
  done
} > sqlc.yaml
